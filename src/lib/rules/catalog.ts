const storeBasePrices = (
  department: DepartmentId,
  productLabelSuffix: string,
  discounterPriceCents: number,
  supermarketPriceCents: number = discounterPriceCents,
  brandOverrides?: Partial<Record<StoreId, string>>,
  priceOverrides?: Partial<Record<StoreId, number>>,
): Record<StoreId, BasePriceEntry> => {
  const storeIds: StoreId[] = ["lidl", "aldi", "rewe", "edeka", "kaufland", "netto", "penny"];
  const result = {} as Record<StoreId, BasePriceEntry>;
  for (const id of storeIds) {
    const brand = brandOverrides?.[id] ?? DEFAULT_STORE_BRANDS[department][id];
    const basePrice =
      id === "rewe" || id === "edeka" ? supermarketPriceCents : discounterPriceCents;
    result[id] = {
      priceCents: priceOverrides?.[id] ?? basePrice,
      productLabel: brand ? `${brand} ${productLabelSuffix}` : productLabelSuffix,
    };
  }
  return result;
};

